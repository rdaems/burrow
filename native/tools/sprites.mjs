// node native/tools/sprites.mjs > native/crates/room/src/sprites_gen.rs
// web/sprites.js's letter grids, as Rust: art() is made to hand back its rows instead of drawing them.
import { readFileSync } from "node:fs";
const src = readFileSync(new URL("../../web/sprites.js", import.meta.url), "utf8")
  .replace("function art(rows, pal = {}) {", "function art(rows, pal = {}) { return { rows, pal };");
const window = {}, document = { createElement: () => ({ getContext: () => ({}) }) };
class Image { set src(_) {} }
new Function("window", "document", "Image", "console", src)(window, document, Image, console);
const S = window.sprites;
const names = ["door", "doorOpen", "window", "clock", "monitor", "laptop", "chair", "counter", "brewer", "pot", "cooler", "bottle", "printer", "stand", "lamp", "chess", "pong"];
const out = ["// generated by native/tools/sprites.mjs from web/sprites.js: do not edit", "",
  "/// the palette: a letter a colour (`s` the floor's shadow)",
  "pub const PAL: &[(char, &str)] = &[" + Object.entries(S.PAL).map(([k, v]) => `('${k}', "${v}")`).join(", ") + "];", ""];
for (const n of names) {
  const a = S.get(n);
  if (!a || !a.rows) throw new Error("no sprite " + n);
  out.push(`pub const ${n.replace(/[A-Z]/g, (c) => "_" + c).toUpperCase()}: &[&str] = &[`);
  for (const r of a.rows) out.push(`    "${r}",`);
  out.push("];", "");
}
out.push("/// every letter grid by its web name", "pub const ALL: &[(&str, &[&str])] = &[" + names.map((n) => `("${n}", ${n.replace(/[A-Z]/g, (c) => "_" + c).toUpperCase()})`).join(", ") + "];");
console.log(out.join("\n"));
